#!/usr/bin/env ruby
# frozen_string_literal: true

# Provider health monitor.
#
# Fetches the live /v2/providers feed and flags missed publishes or unknown currency codes, keeping one GitHub issue per
# affected provider. This surfaces silent freezes and published labels that need a currency registry update.
#
# Issues carry two labels: `provider` (the umbrella every provider issue shares, human-filed or auto) and `health`
# (bot-owned; the discriminator used to find the rolling issues this script manages). `health` must never be applied by
# hand, or this script could match and edit a human's issue.
#
# `publishes_missed` is already cadence-aware in its unit (missed fire-days for daily, missed week/month buckets for
# weekly/monthly), computed server-side, so this script only thresholds it. Thresholds sit above normal lag: daily
# absorbs holiday clusters and T+1 publishing; monthly absorbs in-arrears archives.
#
# Each run, per flagged provider: create an issue if none is open, otherwise refresh its body (so the missed count stays
# current) without commenting. When all checks recover, its issue is commented and closed. Creation is the only
# notification; an ongoing freeze stays quiet.
#
# Run with DRY_RUN=1 to print the decision and bodies without touching issues.

require "English"
require "json"
require "net/http"
require "uri"
require "date"

API = ENV.fetch("API", "https://api.frankfurter.dev/v2/providers")
REPO = ENV.fetch("REPO", "lineofflight/frankfurter")
# `health` is bot-owned and used to find the issues this script manages, so the search filters on it alone; both labels
# are applied on create.
HEALTH_LABEL = "health"
PROVIDER_LABEL = "provider"

# Flag only well past normal lag. See the calibration in the PR that introduced this for why these values.
THRESHOLDS = { "daily" => 8, "weekly" => 2, "monthly" => 2 }.freeze

def fetch_providers
  attempts = 0
  begin
    JSON.parse(Net::HTTP.get(URI(API)))
  rescue OpenSSL::SSL::SSLError, SocketError, Net::OpenTimeout, Net::ReadTimeout, Errno::ECONNRESET
    attempts += 1
    raise if attempts > 3

    sleep(2**attempts)
    retry
  end
end

def flagged(providers)
  flagged_providers = providers.select do |provider|
    stale?(provider) || Array(provider["unknown_currencies"]).any?
  end
  flagged_providers.sort_by { |provider| -(provider["publishes_missed"] || 0) }
end

def stale?(provider)
  threshold = THRESHOLDS[provider["publish_cadence"]]
  threshold && (provider["publishes_missed"] || 0) >= threshold
end

# A stable internal identifier embedded in each issue body, deliberately kept as `provider-health` (not renamed with the
# label) so already-open issues stay matchable. It is what pins an issue to its provider, independent of labels.
def marker(key)
  "<!-- provider-health: #{key} -->"
end

def render_body(provider, today)
  sections = [marker(provider["key"]), "**#{provider["name"]}** (`#{provider["key"]}`)"]
  if stale?(provider)
    sections << <<~MARKDOWN.strip
      This provider has missed more scheduled publishes than normal lag allows. Likely a broken feed (TLS, source change, block), not a holiday gap.

      | Cadence | Last rate | Missed |
      |---------|-----------|--------|
      | #{provider["publish_cadence"]} | #{provider["end_date"]} | #{provider["publishes_missed"]} |
    MARKDOWN
  end

  codes = Array(provider["unknown_currencies"])
  unless codes.empty?
    sections << <<~MARKDOWN.strip
      Unknown currency codes: #{codes.map { |code| "`#{code}`" }.join(", ")}.

      These quotes are stored and available through provider routes, but excluded from blends and the currency catalogue. Check the published labels and add verified entries to `db/seeds/currency_patches.json` or update the Money gem.
    MARKDOWN
  end

  sections << "_Checked #{today} UTC. Auto-generated by `.github/workflows/provider-health.yml`; " \
              "closes when all checks recover._"
  "#{sections.join("\n\n")}\n"
end

def gh(*args)
  output = IO.popen(["gh", *args], &:read)
  raise "gh #{args.join(" ")} failed" unless $CHILD_STATUS.success?

  output
end

# Open health issues keyed by the provider they track.
def open_issues_by_key
  json = gh(
    "issue",
    "list",
    "--repo",
    REPO,
    "--state",
    "open",
    "--label",
    HEALTH_LABEL,
    "--json",
    "number,body",
    "--limit",
    "100",
  )
  JSON.parse(json).each_with_object({}) do |issue, map|
    key = issue["body"].to_s[/<!-- provider-health: (\w+) -->/, 1]
    map[key] = issue["number"] if key
  end
end

def main
  stale = flagged(fetch_providers)
  today = Date.today.to_s

  if ENV["DRY_RUN"]
    warn("DRY_RUN flagged: #{stale.map { |provider| provider["key"] }.inspect}")
    stale.each { |provider| warn(render_body(provider, today)) }
    return
  end

  open_issues = open_issues_by_key

  stale.each do |provider|
    body = render_body(provider, today)
    title = if Array(provider["unknown_currencies"]).any?
              "Unknown currencies: #{provider["key"]}"
            else
              "Stale provider: #{provider["key"]}"
            end
    number = open_issues[provider["key"]]
    if number
      gh("issue", "edit", number.to_s, "--repo", REPO, "--title", title, "--body", body)
    else
      gh(
        "issue",
        "create",
        "--repo",
        REPO,
        "--label",
        PROVIDER_LABEL,
        "--label",
        HEALTH_LABEL,
        "--title",
        title,
        "--body",
        body,
      )
    end
  end

  recovered = open_issues.keys - stale.map { |provider| provider["key"] }
  recovered.each do |key|
    number = open_issues[key]
    gh("issue", "comment", number.to_s, "--repo", REPO, "--body",
       "#{key} passes provider health checks again. Closing.",)
    gh("issue", "close", number.to_s, "--repo", REPO)
  end
end

main if $PROGRAM_NAME == __FILE__
